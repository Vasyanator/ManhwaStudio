#![warn(clippy::all)]
#![warn(clippy::pedantic)]

mod bundle;
#[cfg(test)]
mod derive;
mod install;
mod names;

pub use bundle::{Bundle, NotIncluded, bundle};
pub use install::{InstallError, InstallReport, install, install_dir, installed_build_id};
pub use names::{BUILD_INFO_FILE_NAME, STAMP_FILE_NAME};

// `CHROMIUM_EXTENSION_ID`, generated by build.rs from the manifest `key`.
include!(concat!(env!("OUT_DIR"), "/ids.rs"));

/// The WebSocket `Origin` the Chromium extension connects with: `chrome-extension://<id>`.
#[must_use]
pub fn chromium_origin() -> String {
    format!("chrome-extension://{CHROMIUM_EXTENSION_ID}")
}

#[cfg(test)]
mod tests {
    use base64::Engine as _;
    use sha2::{Digest as _, Sha256};

    use super::{BUILD_INFO_FILE_NAME, CHROMIUM_EXTENSION_ID, chromium_origin};
    use crate::derive::{build_id_of, extension_id_from_public_key};

    const MANIFEST: &str = include_str!("../../../browser-extension/manifest.json");
    const PROTOCOL_TS: &str = include_str!("../../../browser-extension/src/core/protocol.ts");

    /// Id computed outside Rust from the committed manifest key:
    /// `base64 -d | sha256sum | cut -c1-32 | tr 0-9a-f a-p`.
    const EXPECTED_ID: &str = "hgiocpmdmmmfkdlijbpjpekcggdpgfca";

    #[test]
    fn id_mapping_matches_the_chromium_rule() {
        // sha256("") = e3b0c442 98fc1c14 9afbf4c8 996fb924 ...; digit n -> letter n
        // (expected value from `printf "" | sha256sum | cut -c1-32 | tr 0-9a-f a-p`).
        assert_eq!(extension_id_from_public_key(b""), "odlameecjipmbmbejkplpemijjgpljce");
        let id = extension_id_from_public_key(b"any key");
        assert_eq!(id.len(), 32);
        assert!(id.bytes().all(|b| (b'a'..=b'p').contains(&b)), "{id}");
    }

    #[test]
    fn generated_id_is_derived_from_the_committed_manifest_key() {
        let manifest: serde_json::Value = serde_json::from_str(MANIFEST).unwrap_or_else(|err| panic!("{err:?}"));
        let key = manifest["key"].as_str().unwrap_or_else(|| panic!("manifest.json has no key"));
        let der = base64::engine::general_purpose::STANDARD.decode(key).unwrap_or_else(|err| panic!("{err:?}"));
        assert_eq!(extension_id_from_public_key(&der), CHROMIUM_EXTENSION_ID);
        assert_eq!(CHROMIUM_EXTENSION_ID, EXPECTED_ID);
        assert_eq!(chromium_origin(), format!("chrome-extension://{EXPECTED_ID}"));
    }

    #[test]
    fn build_id_is_order_independent_and_content_sensitive() {
        let a = build_id_of(&[("a.js", b"1"), ("b.js", b"2")]);
        assert_eq!(a, build_id_of(&[("b.js", b"2"), ("a.js", b"1")]));
        assert_ne!(a, build_id_of(&[("a.js", b"1"), ("b.js", b"3")]));
        // The length prefix keeps path/content boundaries unambiguous.
        assert_ne!(build_id_of(&[("ab", b"c")]), build_id_of(&[("a", b"bc")]));
        assert_eq!(a.len(), 32);
        // Pinned value: the rule is `sha256(path, 0x00, u64 LE length, bytes ...)[..16]`.
        let mut hasher = Sha256::new();
        hasher.update(b"a.js\0");
        hasher.update(1u64.to_le_bytes());
        hasher.update(b"1");
        hasher.update(b"b.js\0");
        hasher.update(1u64.to_le_bytes());
        hasher.update(b"2");
        assert_eq!(a, hex::encode(&hasher.finalize()[..16]));
    }

    #[test]
    fn build_info_name_mirrors_the_extension() {
        assert!(PROTOCOL_TS.contains(&format!("export const BUILD_INFO_FILE_NAME = \"{BUILD_INFO_FILE_NAME}\";")));
    }
}
