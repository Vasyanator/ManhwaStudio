/*
File: crates/ms-sdcpp/src/ffi/types.rs

Purpose:
`#[repr(C)]` mirrors of the stable-diffusion.cpp C API types the bindings use, field-exact
against the vendored header `vendor/stable-diffusion.h` of the pinned release (sha256
`catalog::PINNED.header_sha256`), including every nested struct and every field the code never touches.

Key items:
- the 16 structs (`SdCtxParams`, `SdImgGenParams`, `SdSampleParams`, … — each names its C type)
- C enums as `#[repr(transparent)]` `i32` newtypes with the constants the code uses
- callback types `SdLogCb`, `SdProgressCb`; the opaque `SdCtx`

Notes:
- Field names are the C names (`Fn_compute_blocks` / `Bn_compute_blocks` become snake case).
  The order, types and layout are pinned by `layout_tests.rs`, whose constants were measured
  once by compiling a C program against `vendor/` with `gcc -m64` (Linux x86_64) and checked
  identical for `x86_64-w64-mingw32-gcc` with `_Static_assert`s (C `bool` = 1 byte, C enums =
  4 bytes on both; plain C structs have the same layout under MSVC on x64).
- Values are always initialized by the library's own `*_init` functions, never by Rust
  defaults; the code then overwrites only the fields it sets.
- A C enum field may hold a value Rust does not name, so enums are integers, never Rust enums.
- Regenerated by hand for a new release: compare the new header with the vendored one.
*/

use std::ffi::{c_char, c_int, c_void};


/// Declares a C enum as a transparent `i32` newtype with named constants.
macro_rules! c_enum {
    ($(#[$doc:meta])* $name:ident { $($(#[$cdoc:meta])* $konst:ident = $value:expr),* $(,)? }) => {
        $(#[$doc])*
        #[repr(transparent)]
        #[derive(Debug, Clone, Copy, PartialEq, Eq)]
        pub struct $name(pub i32);

        impl $name {
            $($(#[$cdoc])* pub const $konst: Self = Self($value);)*
        }
    };
}

